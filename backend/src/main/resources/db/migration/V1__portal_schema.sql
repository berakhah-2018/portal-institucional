CREATE TABLE portal_user (
    id BIGSERIAL PRIMARY KEY,
    google_subject VARCHAR(255) NOT NULL UNIQUE,
    email VARCHAR(320) NOT NULL UNIQUE,
    display_name VARCHAR(200) NOT NULL,
    role VARCHAR(16) NOT NULL CHECK (role IN ('ADMIN', 'EDITOR', 'LECTOR')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE portal_image (
    id BIGSERIAL PRIMARY KEY,
    drive_file_id VARCHAR(255) NOT NULL UNIQUE,
    uploaded_by VARCHAR(320) NOT NULL,
    display_name VARCHAR(255) NOT NULL,
    mime_type VARCHAR(100) NOT NULL,
    visible_to VARCHAR(64) NOT NULL DEFAULT 'ADMIN,EDITOR,LECTOR',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE portal_content (
    id BIGSERIAL PRIMARY KEY,
    title VARCHAR(240) NOT NULL,
    body TEXT NOT NULL,
    status VARCHAR(16) NOT NULL CHECK (status IN ('DRAFT', 'PUBLISHED')),
    visible_to VARCHAR(64) NOT NULL DEFAULT 'ADMIN,EDITOR,LECTOR',
    created_by VARCHAR(320) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
